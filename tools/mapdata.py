# Builds Data/Maps.lua and Data/AreaNames.lua from the 3.3.5a client tables (WorldMapArea, DungeonMap,
# AreaTable, Map). Map keys stay the uiMap numbers the guides use; tools/uimap_ids.lua lists which
# uiMap number belongs to which 3.3.5 map area (+ dungeon level).
import struct, re, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'mpq'))
from dbc import load
D = os.path.join(os.path.dirname(__file__), 'dbc')
SRC = '/home/claude/qq/src/Data/'

wma = {}
rows, f, rs, s = load(D + '/WorldMapArea.dbc')
for r in rows:
    v = struct.unpack('<3iI4f3i', r)
    wma[v[0]] = dict(id=v[0], map=v[1], area=v[2], internal=s(v[3]), left=v[4], right=v[5], top=v[6], bottom=v[7], deffloor=v[9])
# zones of one continent shown on another one (Eversong / Ghostlands on the Eastern Kingdoms, Azuremyst / Bloodmyst on Kalimdor)
transforms = []
rows, f, rs, s = load(D + '/WorldMapTransforms.dbc')
for r in rows:
    v = struct.unpack('<2i4fi2fi', r)
    if v[1] != v[6]:
        transforms.append(dict(map=v[1], minx=v[2], miny=v[3], maxx=v[4], maxy=v[5], newmap=v[6], offx=v[7], offy=v[8]))
floors = {}
rows, f, rs, s = load(D + '/DungeonMap.dbc')
for r in rows:
    v = struct.unpack('<3i4fi', r)
    floors[(v[1], v[2])] = dict(minx=v[3], maxx=v[4], miny=v[5], maxy=v[6], wma=v[7])
areas = {}
rows, f, rs, s = load(D + '/AreaTable.dbc')
for r in rows:
    v = struct.unpack('<%di' % f, r)
    areas[v[0]] = s(v[11])
mapnames = {}
rows, f, rs, s = load(D + '/Map.dbc')
for r in rows:
    v = struct.unpack('<%di' % f, r)
    mapnames[v[0]] = s(v[5])

ids = {}
for line in open(os.path.join(os.path.dirname(__file__), 'uimap_ids.lua')):
    m = re.match(r'\s*\[(\d+)\]\s*=\s*([\d.]+),', line)
    if m: ids[int(m.group(1))] = m.group(2)

def fmt(x):
    return ('%.6f' % x).rstrip('0').rstrip('.')

out, missing = [], []
for ui in sorted(ids):
    key = ids[ui]
    area_api, _, level = key.partition('.')
    w = wma.get(int(area_api) - 1)  # GetCurrentMapAreaID() = WorldMapArea id + 1
    if not w: missing.append(ui); continue
    level = int(level or 0)
    # dungeon levels: maps with default floor -1 show the whole map as level 1
    floor = level - 1 if w['deffloor'] == -1 else level
    fl = floors.get((w['map'], floor)) if level >= 1 else None
    instance = w['map']
    if fl:
        left, top = fl['maxx'], fl['maxy']
        width, height = fl['maxx'] - fl['minx'], fl['maxy'] - fl['miny']
    else:
        left, top = w['left'], w['top']
        width, height = w['left'] - w['right'], w['top'] - w['bottom']
        for t in transforms:
            if t['map'] == w['map'] and t['minx'] <= top <= t['maxx'] and t['miny'] <= left <= t['maxy'] and w['area'] != 0:
                top, left, instance = top + t['offx'], left + t['offy'], t['newmap']
                break
    if w['area'] == 0:
        name = mapnames.get(w['map'], w['internal'])
        mtype = 2 if w['map'] in (0, 1, 530, 571) else 4
    else:
        name = areas.get(w['area'], w['internal'])
        mtype = 4 if level or w['map'] not in (0, 1, 530, 571, 609) else 3
    if width <= 0 or height <= 0: missing.append(ui); continue
    name = name.replace('\\', '\\\\').replace('"', '\\"')
    out.append('    [%d] = {%s, %s, %s, %s, mapType = %d, mapID = %s, instance = %d, name = "%s"},' % (
        ui, fmt(width), fmt(height), fmt(left), fmt(top), mtype, key, instance, name))

# uiMaps the 3.3.5 client has no map for (sub maps of later clients) - kept by hand
extra = open(os.path.join(os.path.dirname(__file__), 'uimap_extra.lua')).read().strip()
with open(SRC + 'Maps.lua', 'w') as fh:
    fh.write('-- Map bounds (uiMap number -> world coordinates) for the 3.3.5a client.\n')
    fh.write('-- Generated by tools/mapdata.py from the client tables WorldMapArea, DungeonMap, AreaTable and Map.\n')
    fh.write('-- {width, height, left, top}: x_world = left - width * x, y_world = top - height * y\n')
    fh.write('local _, QQ = ...\nQQ.maps = {\n' + '\n'.join(out) + '\n' + extra + '\n}\n')
with open(SRC + 'AreaNames.lua', 'w') as fh:
    fh.write('-- AreaTable id -> English name (3.3.5a). Generated by tools/mapdata.py from the client table AreaTable.\n')
    fh.write('local _, QQ = ...\nQQ.areaNames = {\n')
    for a in sorted(areas):
        n = areas[a].replace('\\', '\\\\').replace('"', '\\"')
        if n: fh.write('    [%d] = "%s",\n' % (a, n))
    fh.write('}\n')
print('maps', len(out), 'missing', missing)
