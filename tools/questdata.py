# Builds Data/QuestData.lua (quests used by the guides: name, levels, pre / follow-up quests)
# from a 3.3.5 world database dump (quest_template + quest_template_addon, tools/sql).
import re, os
T = os.path.dirname(os.path.abspath(__file__))

def columns(sql):
    m = re.search(r'CREATE TABLE `\w+` \((.*?)\) ENGINE', sql, re.S)
    return [c for c in re.findall(r'^\s*`(\w+)`', m.group(1), re.M)]

def rows(sql):
    body = sql[sql.index('INSERT INTO'):]
    i, n = 0, len(body)
    while True:
        i = body.find('(', i)
        if i < 0: return
        vals, cur, j = [], [], i + 1
        while j < n:
            c = body[j]
            if c == "'":
                j += 1
                s = []
                while body[j] != "'" or body[j + 1:j + 2] == "'":
                    if body[j] == '\\': s.append(body[j + 1]); j += 2; continue
                    if body[j] == "'": s.append("'"); j += 2; continue
                    s.append(body[j]); j += 1
                cur = ''.join(s); vals.append(cur); cur = None; j += 1
            elif c == ',':
                if cur is not None: vals.append(''.join(cur).strip())
                cur = []; j += 1
            elif c == ')':
                if cur is not None: vals.append(''.join(cur).strip())
                yield vals; i = j + 1; break
            else:
                if cur is None: cur = []
                cur.append(c); j += 1

def table(name):
    sql = open(os.path.join(T, 'sql', name + '.sql'), encoding='utf8').read()
    cols = columns(sql)
    out = {}
    for v in rows(sql):
        if len(v) != len(cols): continue
        d = dict(zip(cols, v))
        out[int(d['ID'])] = d
    return out

qt, qa = table('quest_template'), table('quest_template_addon')
want = set(int(l) for l in open(os.path.join(T, 'guidequests.txt')) if l.strip())

def num(d, k):
    try: return int(float(d.get(k, 0) or 0))
    except ValueError: return 0

preAll, preOne = {}, {}
for q, a in qa.items():
    prev = num(a, 'PrevQuestID')
    if prev > 0: preAll.setdefault(q, set()).add(prev)
# NextQuestID: the next quest needs this one (one of a group, or all of a group with ExclusiveGroup < 0)
for q, a in qa.items():
    nxt = num(a, 'NextQuestID')
    if nxt <= 0: continue
    if num(a, 'ExclusiveGroup') < 0: preAll.setdefault(nxt, set()).add(q)
    else: preOne.setdefault(nxt, set()).add(q)

follow = {}
for q in list(preAll) + list(preOne):
    for p in preAll.get(q, set()) | preOne.get(q, set()):
        if p in want and q in want: follow.setdefault(p, set()).add(q)

def lst(s): return '{' + ','.join(str(x) for x in sorted(s)) + '}' if s else 'nil'
def lua(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'

lines = []
for q in sorted(want):
    d = qt.get(q)
    if not d: continue
    parts = [lua(d.get('LogTitle') or ''), str(num(d, 'QuestLevel')), str(num(d, 'MinLevel')),
             lst(follow.get(q)), lst(preAll.get(q, set()) & (want | set(preAll.get(q, set())))), lst(preOne.get(q))]
    while parts[-1] == 'nil': parts.pop()
    lines.append('[%d]={%s},' % (q, ','.join(parts)))
with open('/home/claude/qq/src/Data/QuestData.lua', 'w') as fh:
    fh.write('-- Quest data for the quests used by the guides (3.3.5a).\n')
    fh.write('-- Generated by tools/questdata.py from a 3.3.5 world database (quest_template, quest_template_addon).\n')
    fh.write('-- [questID] = {name, questLevel, requiredLevel, {follow-up quests}, {all pre quests}, {one of these pre quests}}\n')
    fh.write('local _, QQ = ...\nQQ.questData = {\n' + '\n'.join(lines) + '\n}\n')
print(len(lines), 'of', len(want))
